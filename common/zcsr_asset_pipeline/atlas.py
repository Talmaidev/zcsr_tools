#!/usr/bin/env python3
"""Generic offline atlas baker.

Packs ANIM strips from a manifest into one or more RGBA atlas pages and writes
an atlas manifest. Strips too tall/wide for a page stay standalone; the input
manifest and PNGs are never modified.

This tool only arranges already-baked frame strips. It does not decode GIFs and
does not concatenate source sprite fragments.
"""
from __future__ import annotations

import argparse
import pathlib

from PIL import Image

PAD = 2
PAGE_W = 2048
PAGE_H = 2048
MAX_PAGES = 16


def parse_manifest(path: pathlib.Path) -> tuple[list[str], list[tuple[str, str]]]:
    lines = path.read_text(encoding="utf-8").splitlines()
    anims: list[tuple[str, str]] = []
    for line in lines:
        if not line.startswith("ANIM "):
            continue
        parts = line.split()
        if len(parts) < 3:
            raise SystemExit(f"bad ANIM line: {line}")
        anims.append((parts[1], parts[2]))
    return lines, anims


def pack_pages(
    rects: list[tuple[str, str, int, int]],
    page_w: int = PAGE_W,
    page_h: int = PAGE_H,
    max_pages: int = MAX_PAGES,
):
    """Return pages[(used_h, placements[(id,path,w,h,x,y)])], standalone ids."""
    pages: list[tuple[int, list[tuple[str, str, int, int, int, int]]]] = []
    standalone: list[tuple[str, str, int, int]] = []
    shelf_rects: list[tuple[str, str, int, int]] = []

    for aid, rel, w, h in rects:
        if w + PAD * 2 > page_w or h + PAD * 2 > page_h:
            standalone.append((aid, rel, w, h))
        else:
            shelf_rects.append((aid, rel, w, h))

    shelf_rects.sort(key=lambda r: (r[3], r[2]), reverse=True)
    while shelf_rects:
        if len(pages) >= max_pages:
            standalone.extend(shelf_rects)
            break
        x = PAD
        y = PAD
        row_h = 0
        placements: list[tuple[str, str, int, int, int, int]] = []
        remaining: list[tuple[str, str, int, int]] = []
        for aid, rel, w, h in shelf_rects:
            if x + w + PAD > page_w:
                x = PAD
                y += row_h + PAD
                row_h = 0
            if y + h + PAD > page_h:
                remaining.append((aid, rel, w, h))
                continue
            placements.append((aid, rel, w, h, x, y))
            x += w + PAD
            row_h = max(row_h, h)
        used_h = y + row_h + PAD
        if not placements:
            standalone.extend(remaining)
            break
        pages.append((used_h, placements))
        shelf_rects = remaining
    return pages, standalone


def pack_project(
    project: pathlib.Path,
    manifest_rel: str = "assets/manifest.txt",
    out_dir_rel: str = "assets/atlas",
    out_manifest_rel: str = "assets/manifest_atlas.txt",
    page_w: int = PAGE_W,
    page_h: int = PAGE_H,
    max_pages: int = MAX_PAGES,
    manifest_header: str | None = None,
    atlas_prefix: str = "assets/atlas/",
) -> pathlib.Path:
    project = pathlib.Path(project)
    manifest_path = project / manifest_rel
    out_dir = project / out_dir_rel
    out_manifest = project / out_manifest_rel

    lines, anims = parse_manifest(manifest_path)
    rects: list[tuple[str, str, int, int]] = []
    images: dict[str, Image.Image] = {}
    for aid, rel in anims:
        p = project / rel
        if not p.is_file():
            raise SystemExit(f"missing animation png: {p}")
        im = Image.open(p).convert("RGBA")
        images[aid] = im
        rects.append((aid, rel, im.width, im.height))

    pages, standalone = pack_pages(rects, page_w, page_h, max_pages)
    out_dir.mkdir(parents=True, exist_ok=True)
    out: list[str] = [
        manifest_header or "# Atlas manifest v1 (generated by zcsr_asset_pipeline.atlas)",
    ]
    bindings: list[str] = []
    for page_index, (used_h, placements) in enumerate(pages):
        page = Image.new("RGBA", (page_w, page_h), (0, 0, 0, 0))
        for aid, _rel, w, h, x, y in placements:
            page.alpha_composite(images[aid], (x, y))
        page_path = out_dir / f"page_{page_index}.png"
        page.save(page_path, optimize=True)
        page_id = f"page_{page_index}"
        out.append(f"PAGE {page_id} {atlas_prefix}{page_path.name} {page_w} {page_h}")
        for aid, _rel, _w, _h, x, y in placements:
            bindings.append(f"ATLAS {aid} {page_id} {x} {y}")
        print(
            f"atlas page {page_id}: {page_w}x{page_h}, "
            f"{len(placements)} anims, used_h={used_h}"
        )

    for line in lines:
        if line.startswith("ANIM "):
            out.append(line)
    out.extend(bindings)
    for line in lines:
        if line.startswith("IMG "):
            out.append(line)
    out_manifest.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"standalone anims: {len(standalone)}: " + ", ".join(a[0] for a in standalone))
    print(f"manifest: {out_manifest}")
    return out_manifest


def main(argv: list[str] | None = None, default_project: pathlib.Path | None = None,
         default_manifest_header: str | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--project", default=str(default_project or pathlib.Path.cwd()))
    parser.add_argument("--manifest", default="assets/manifest.txt")
    parser.add_argument("--out-dir", default="assets/atlas")
    parser.add_argument("--output", default="assets/manifest_atlas.txt")
    parser.add_argument("--page-width", type=int, default=PAGE_W)
    parser.add_argument("--page-height", type=int, default=PAGE_H)
    parser.add_argument("--max-pages", type=int, default=MAX_PAGES)
    parser.add_argument("--atlas-prefix", default="assets/atlas/")
    parser.add_argument("--manifest-header", default=default_manifest_header)
    args = parser.parse_args(argv)

    pack_project(
        pathlib.Path(args.project),
        args.manifest,
        args.out_dir,
        args.output,
        args.page_width,
        args.page_height,
        args.max_pages,
        args.manifest_header,
        args.atlas_prefix,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
